"""Core text analytics for the Advanced Text Intelligence project."""
from collections import Counter
import re
import unicodedata

WORD_RE = re.compile(r"\b[\w'-]+\b", re.UNICODE)
SENTENCE_RE = re.compile(r"[.!?]+(?=\s|$)")

def normalize_text(text: str, *, casefold: bool = True, remove_accents: bool = False) -> str:
    """Normalize whitespace and optionally case and diacritics."""
    text = unicodedata.normalize("NFC", text)
    if remove_accents:
        decomposed = unicodedata.normalize("NFD", text)
        text = "".join(ch for ch in decomposed if unicodedata.category(ch) != "Mn")
    if casefold:
        text = text.casefold()
    return re.sub(r"\s+", " ", text).strip()

def get_words(text: str) -> list[str]:
    return WORD_RE.findall(text)

def analyze_text(text: str) -> dict:
    chars = Counter(text)
    words = get_words(text)
    normalized_words = [w.casefold() for w in words]
    sentences = [s.strip() for s in re.split(r"(?<=[.!?])\s+", text.strip()) if s.strip()]
    letters = sum(ch.isalpha() for ch in text)
    digits = sum(ch.isdigit() for ch in text)
    whitespace = sum(ch.isspace() for ch in text)
    punctuation = sum(unicodedata.category(ch).startswith("P") for ch in text)
    vowels = sum(ch.casefold() in "aeiou" for ch in text if ch.isalpha())
    consonants = sum(ch.isalpha() and ch.casefold() not in "aeiou" for ch in text)
    return {
        "characters": len(text),
        "characters_without_whitespace": sum(not ch.isspace() for ch in text),
        "letters": letters,
        "digits": digits,
        "whitespace": whitespace,
        "punctuation": punctuation,
        "vowels": vowels,
        "consonants": consonants,
        "words": len(words),
        "unique_words": len(set(normalized_words)),
        "sentences": len(sentences),
        "average_word_length": round(sum(map(len, words)) / len(words), 2) if words else 0,
        "top_words": Counter(normalized_words).most_common(10),
        "character_frequency": chars.most_common(15),
        "longest_word": max(words, key=len, default=""),
        "shortest_word": min(words, key=len, default=""),
    }

def is_palindrome(text: str, *, ignore_non_alphanumeric: bool = True) -> bool:
    candidate = text.casefold()
    if ignore_non_alphanumeric:
        candidate = "".join(ch for ch in candidate if ch.isalnum())
    return candidate == candidate[::-1]

def are_anagrams(first: str, second: str) -> bool:
    clean = lambda s: Counter(ch.casefold() for ch in s if ch.isalnum())
    return clean(first) == clean(second)

def duplicate_characters(text: str, *, ignore_spaces: bool = True) -> dict[str, int]:
    source = [ch.casefold() for ch in text if not (ignore_spaces and ch.isspace())]
    counts = Counter(source)
    return {ch: n for ch, n in counts.items() if n > 1}

def first_non_repeating_character(text: str) -> str | None:
    counts = Counter(text.casefold())
    for ch in text:
        if counts[ch.casefold()] == 1:
            return ch
    return None

def longest_word(text: str) -> str:
    return max(get_words(text), key=len, default="")

def compress_runs(text: str) -> str:
    """Run-length encode consecutive repeated characters; e.g. aaabb -> a3b2."""
    if not text:
        return ""
    result = []
    current, count = text[0], 1
    for ch in text[1:]:
        if ch == current:
            count += 1
        else:
            result.append(f"{current}{count}")
            current, count = ch, 1
    result.append(f"{current}{count}")
    return "".join(result)

def expand_runs(encoded: str) -> str:
    """Decode run-length format generated by compress_runs (supports digits in source imperfectly)."""
    parts = re.findall(r"(.)(\d+)", encoded)
    if not encoded:
        return ""
    if not parts or "".join(ch + count for ch, count in parts) != encoded:
        raise ValueError("Invalid run-length encoded input.")
    return "".join(ch * int(count) for ch, count in parts)
